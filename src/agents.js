import { mkdtemp, readFile, rename, rm, writeFile } from "node:fs/promises";
import path from "node:path";

const ownershipMarker = "<!-- @studio/eleventy-preset:agents -->";
const sharedSource = new URL("../templates/agents.shared.md", import.meta.url);
const packageSource = new URL("../package.json", import.meta.url);
const localSource = "docs/agents.site.md";

function normalizeMarkdown(source) {
  return source.replace(/\r\n?/g, "\n").replace(/\n+$/, "");
}

async function readInput(source, label) {
  try {
    return await readFile(source, "utf8");
  } catch (error) {
    throw new Error(`Cannot read ${label} (${error.code}). See the README local guidance template for ${localSource}.`, { cause: error });
  }
}

async function generateGuidance(root) {
  const shared = await readInput(sharedSource, "bundled templates/agents.shared.md");
  const local = await readInput(path.join(root, localSource), localSource);
  const { version } = JSON.parse(await readInput(packageSource, "preset package.json"));
  const header = `${ownershipMarker}
<!-- Generated by studio-eleventy agents sync; do not edit this output.
Preset: @studio/eleventy-preset@${version}
Generator format: 1
Sources: @studio/eleventy-preset/templates/agents.shared.md, docs/agents.site.md
Edit the maintained sources, then run studio-eleventy agents sync again.
-->`;
  return `${header}\n\n${normalizeMarkdown(shared)}\n\n${normalizeMarkdown(local)}\n`;
}

async function readOutput(output) {
  try {
    return await readFile(output, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw new Error(`Cannot read AGENTS.md (${error.code}).`, { cause: error });
  }
}

export async function runAgents(args, root = process.cwd()) {
  if (args.length !== 1 || !["sync", "check"].includes(args[0])) {
    throw new Error("Usage: studio-eleventy agents <sync|check>");
  }
  const expected = await generateGuidance(root);
  const output = path.join(root, "AGENTS.md");
  const current = await readOutput(output);
  if (current !== null && current.split(/\r?\n/, 1)[0] !== ownershipMarker) {
    throw new Error("AGENTS.md is unmanaged; refusing to overwrite it. Review and preserve existing instructions, move essential local rules into docs/agents.site.md, deliberately rename or remove the old AGENTS.md, then run studio-eleventy agents sync.");
  }
  if (current === expected) return "AGENTS.md is up to date.";
  if (args[0] === "check") {
    throw new Error(`AGENTS.md is ${current === null ? "missing" : "stale"}. Run studio-eleventy agents sync, review the output, and commit it.`);
  }
  const temporaryDirectory = await mkdtemp(path.join(root, ".agents-sync-"));
  try {
    const temporaryOutput = path.join(temporaryDirectory, "AGENTS.md");
    await writeFile(temporaryOutput, expected, "utf8");
    await rename(temporaryOutput, output);
  } finally {
    await rm(temporaryDirectory, { recursive: true, force: true });
  }
  return "Synchronized AGENTS.md. Review and commit the generated guidance.";
}
